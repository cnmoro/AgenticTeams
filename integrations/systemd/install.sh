#!/usr/bin/env bash
# Installs AgenticTeams as a systemd user service (24/7; starts at boot with linger).
# Listens on 127.0.0.1 and, if Tailscale is up, also on the tailnet IP (it does not use
# serve/funnel, so nothing is exposed to the internet).
#
#   integrations/systemd/install.sh            # install/update and (re)start
#   integrations/systemd/install.sh --remove   # stop and remove
#   PORT=8765 PYTHON=/caminho/python3 integrations/systemd/install.sh
#   LISTEN_ALSO=192.168.1.20 integrations/systemd/install.sh   # extra addresses (e.g. LAN), comma-separated
set -euo pipefail
REPO=$(cd "$(dirname "$0")/../.." && pwd)
UNIT=$HOME/.config/systemd/user/agentic-teams.service
PORT=${PORT:-8765}
PYTHON=${PYTHON:-$(command -v python3)}

if [[ ${1:-} == --remove ]]; then
  systemctl --user disable --now agentic-teams.service 2>/dev/null || true
  rm -f "$UNIT"; systemctl --user daemon-reload
  echo "removed"; exit 0
fi

"$PYTHON" -c "import aiohttp" || { echo "python $PYTHON has no aiohttp; set PYTHON=..." >&2; exit 1; }

ARGS="--host 127.0.0.1"
TS_IP="" TS_NAME=""
if command -v tailscale >/dev/null && TS_IP=$(tailscale ip -4 2>/dev/null | head -1) && [[ -n $TS_IP ]]; then
  ARGS+=" --host $TS_IP"
  TS_NAME=$(tailscale status --self --json 2>/dev/null | "$PYTHON" -c \
    "import json,sys; print(json.load(sys.stdin)['Self']['DNSName'].rstrip('.'))" 2>/dev/null || true)
  if [[ -n $TS_NAME ]]; then
    ARGS+=" --allow-host $TS_NAME --allow-host ${TS_NAME%%.*}"
  fi
fi

# Extra addresses (e.g. the local network IP). Plain HTTP on that network: use only on a trusted
# network, with a fixed IP (DHCP reservation). Never 0.0.0.0.
LISTEN_ALSO=${LISTEN_ALSO:-}
if [[ -z $LISTEN_ALSO && -f $UNIT ]]; then  # reinstalling keeps the extras already configured
  LISTEN_ALSO=$(sed -n 's/^# LISTEN_ALSO=//p' "$UNIT")
fi
for h in ${LISTEN_ALSO//,/ }; do
  [[ $h == 0.0.0.0 || $h == :: ]] && { echo "do not use $h" >&2; exit 1; }
  ARGS+=" --host $h"
done

if [[ $(loginctl show-user "$USER" -p Linger --value 2>/dev/null) != yes ]]; then
  echo "WARNING: linger is off; the service only runs while you are logged in. Turn it on with: sudo loginctl enable-linger $USER" >&2
fi

mkdir -p "$(dirname "$UNIT")"
cat > "$UNIT" <<UNIT
# Generated by $REPO/integrations/systemd/install.sh; run it again to update.
# LISTEN_ALSO=$LISTEN_ALSO
[Unit]
Description=AgenticTeams (chat between Claude Code agents)
After=network-online.target
Wants=network-online.target

[Service]
ExecStart=$PYTHON $REPO/bin/at-server $ARGS --port $PORT
Restart=always
RestartSec=5
Environment=PYTHONUNBUFFERED=1

[Install]
WantedBy=default.target
UNIT

systemctl --user daemon-reload
systemctl --user enable agentic-teams.service >/dev/null
systemctl --user restart agentic-teams.service
sleep 1.5
systemctl --user --no-pager --lines=0 status agentic-teams.service | head -5
echo
echo "local:     http://127.0.0.1:$PORT"
if [[ -n $TS_IP ]]; then echo "tailscale: http://${TS_NAME:-$TS_IP}:$PORT  (or http://$TS_IP:$PORT)"; fi
for h in ${LISTEN_ALSO//,/ }; do echo "extra:     http://$h:$PORT"; done
echo "logs:      journalctl --user -u agentic-teams -f"
